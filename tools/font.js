#!/usr/bin/env node
/* DEEPCORE font vendoring (M-HIRES Phase 2.5).
   Usage: node tools/font.js [path/to/source.ttf]

   Regenerates vendor/deepcore-mono.css — an @font-face carrying a subsetted
   WOFF2 as a data URI. Run it after adding a glyph to the game (a bark, an
   art asset, a data table); `node tools/glyphs.js` is the inventory and this
   script subsets to exactly that, so the two cannot drift.

   WHY VENDOR AT ALL. The game is characters on a grid, so the font IS the
   art, and we cannot see what other people's machines render. The stack in
   render.js already lost this bet once: it listed no macOS face, so a Mac
   fell through to Courier New and every box-drawing and block glyph
   degraded — invisible from a Linux box. Patching a stack is guesswork about
   other people's systems; vendoring ends the guessing. SPEC3 §0 law 6 makes
   readability the objective, and rule 7 permits a vendored asset that
   demonstrably improves the player's experience.

   WHY NOT A CODE PAGE. Read vendor/README.md: `node tools/glyphs.js` reports
   43 glyphs outside CP437, including the drill gear, the core charge, the
   belt and the cores currency. That analysis stands and is not reopened here.

   BUILD-TIME ONLY. This needs Python with fontTools + brotli; the game, the
   test suites and tools/build.js need none of it, because the generated
   stylesheet is committed. */
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const root = path.join(__dirname, '..');
const FAMILY = 'Deepcore Mono';
const OUT_CSS = path.join(root, 'vendor', 'deepcore-mono.css');
const OUT_WOFF2 = path.join(root, 'vendor', 'deepcore-mono.woff2');

// The source face. DejaVu Sans Mono is what every glyph in this game was
// chosen against, and its license permits redistributing a renamed
// derivative — see vendor/LICENSE-font.txt, which must ship beside it.
const DEFAULT_SRC = '/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf';
const src = process.argv[2] || DEFAULT_SRC;
if (!fs.existsSync(src)) {
  console.error('font: source face not found: ' + src);
  console.error('font: pass one as an argument, e.g. node tools/font.js /path/to/Mono.ttf');
  process.exit(1);
}

const inv = require('./glyphs.js');
const cps = Array.from(new Set(inv.codepoints)).sort((a, b) => a - b);
const cpsFile = path.join(root, 'vendor', '.codepoints.tmp');
fs.writeFileSync(cpsFile, cps.map((c) => c.toString(16)).join('\n') + '\n');

try {
  const out = execFileSync('python3',
    [path.join(__dirname, 'subset_font.py'), src, cpsFile, OUT_WOFF2, FAMILY],
    { encoding: 'utf8' });
  process.stdout.write(out);
} catch (e) {
  console.error('font: subsetting failed. It needs fontTools and brotli:');
  console.error('font:   python3 -m pip install --user fonttools brotli');
  if (e.stderr) process.stderr.write(e.stderr);
  process.exit(1);
} finally {
  fs.unlinkSync(cpsFile);
}

const woff2 = fs.readFileSync(OUT_WOFF2);
const b64 = woff2.toString('base64');

// `font-display: block` on purpose. `swap` would paint one or more frames in
// the fallback face and then reflow — on a character grid that is a visible
// shear of every row, because flush() batches a run of cells into one
// fillText scaled by the advance it measured. Better a beat of nothing than a
// frame of garbage. render.js re-measures on document.fonts.ready regardless.
const css = [
  '/* DEEPCORE — vendored font (M-HIRES Phase 2.5). GENERATED by',
  ' * `node tools/font.js`; do not hand-edit.',
  ' *',
  ' * ' + FAMILY + ': a subset of DejaVu Sans Mono, renamed as its license',
  ' * requires for modified versions, containing exactly the ' + cps.length,
  ' * codepoints `node tools/glyphs.js` reports the game can draw. Embedded as',
  ' * a data URI so the single-file build and file:// both work with no CDN —',
  ' * the artifact CSP blocks external hosts anyway.',
  ' *',
  ' * Full license: vendor/LICENSE-font.txt (Bitstream Vera).',
  ' * Copyright (c) 2003 by Bitstream, Inc. All Rights Reserved.',
  ' * Bitstream Vera is a trademark of Bitstream, Inc.',
  ' * DejaVu changes are in public domain.',
  ' */',
  '@font-face {',
  '  font-family: "' + FAMILY + '";',
  '  font-style: normal;',
  '  font-weight: 400;',
  '  font-display: block;',
  '  src: url(data:font/woff2;base64,' + b64 + ') format("woff2");',
  '}',
  '',
].join('\n');

fs.writeFileSync(OUT_CSS, css);
console.log('font: wrote ' + path.relative(root, OUT_WOFF2) +
  ' (' + (woff2.length / 1024).toFixed(1) + ' KiB, ' + cps.length + ' codepoints)');
console.log('font: wrote ' + path.relative(root, OUT_CSS) +
  ' (' + (css.length / 1024).toFixed(1) + ' KiB as base64)');
